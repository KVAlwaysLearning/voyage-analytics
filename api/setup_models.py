"""One-time setup: unpack the model files from the three Colab output zips and pin library versions.

Usage (from the api/ folder):
    python setup_models.py                 # looks for the zips here and in the parent folder
    python setup_models.py path/to/zips    # or tell it where they are

What it does
  1. Copies every file inside <zip>/models/ into ./models/
  2. Reads the library versions MLflow recorded when the models were trained in Colab
     (scikit-learn, xgboost, numpy, pandas, scipy) and the Python version,
     and writes them into requirements.txt and the Dockerfile.
     Pickled models only load reliably with the SAME versions they were trained with.
"""
import glob
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(HERE, 'models')
ZIPS = ['flight_price_outputs', 'gender_outputs', 'recommender_outputs']
PINNED = ['numpy', 'pandas', 'scikit-learn', 'scipy', 'xgboost']
APP_REQUIREMENTS = ['flask==3.1.1', 'flask-cors==6.0.1', 'gunicorn==23.0.0', 'joblib']


def find_zip(stem, folders):
    for folder in folders:
        hits = sorted(glob.glob(os.path.join(folder, f'{stem}*.zip')))
        if hits:
            return hits[0]
    return None


def main():
    folders = [sys.argv[1]] if len(sys.argv) > 1 else [HERE, os.path.dirname(HERE)]
    os.makedirs(MODEL_DIR, exist_ok=True)
    versions, python_version = {}, None

    for stem in ZIPS:
        path = find_zip(stem, folders)
        if path is None:
            sys.exit(f'ERROR: {stem}.zip not found in {folders}. Upload it and run again.')
        with zipfile.ZipFile(path) as z:
            copied = 0
            for name in z.namelist():
                parts = name.split('/')
                # files directly inside <root>/models/
                if len(parts) == 3 and parts[1] == 'models' and parts[2] and not parts[2].endswith('.pyc'):
                    with open(os.path.join(MODEL_DIR, parts[2]), 'wb') as f:
                        f.write(z.read(name))
                    copied += 1
                # versions recorded by MLflow next to the logged sklearn model
                if name.endswith('artifacts/model/requirements.txt'):
                    for line in z.read(name).decode().splitlines():
                        m = re.match(r'^([A-Za-z0-9_\-]+)==([^\s;]+)', line.strip())
                        if m and m.group(1).lower() in PINNED:
                            pkg, ver = m.group(1).lower(), m.group(2)
                            if pkg in versions and versions[pkg] != ver:
                                print(f'  note: {pkg} {versions[pkg]} vs {ver} in different zips - keeping {versions[pkg]}')
                            versions.setdefault(pkg, ver)
                if name.endswith('artifacts/model/python_env.yaml') and python_version is None:
                    m = re.search(r'python:\s*([0-9]+\.[0-9]+)', z.read(name).decode())
                    if m:
                        python_version = m.group(1)
        print(f'{os.path.basename(path)}: copied {copied} model files')

    missing = [p for p in PINNED if p not in versions]
    if missing:
        print('WARNING: no recorded version for', missing, '- they will be installed unpinned')

    # xgboost-cpu is the same library without the large GPU libraries (much smaller Docker image); available from 2.1
    lines = []
    for pkg in PINNED:
        ver = versions.get(pkg)
        if pkg == 'xgboost':
            major_minor = tuple(int(x) for x in (ver or '0.0').split('.')[:2])
            name = 'xgboost-cpu' if major_minor >= (2, 1) else 'xgboost'
            lines.append(f'{name}=={ver}' if ver else name)
        else:
            lines.append(f'{pkg}=={ver}' if ver else pkg)
    with open(os.path.join(HERE, 'requirements.txt'), 'w') as f:
        f.write('# Generated by setup_models.py - model libraries pinned to the versions used in Colab\n')
        f.write('\n'.join(lines + APP_REQUIREMENTS) + '\n')
    print('requirements.txt written:', ', '.join(lines))

    if python_version:
        dockerfile = os.path.join(HERE, 'Dockerfile')
        with open(dockerfile) as f:
            text = f.read()
        text = re.sub(r'ARG PYTHON_VERSION=[0-9.]+', f'ARG PYTHON_VERSION={python_version}', text)
        with open(dockerfile, 'w') as f:
            f.write(text)
        print(f'Dockerfile: Python {python_version} (same as Colab)')

    print('models/ now contains:', sorted(os.listdir(MODEL_DIR)))


if __name__ == '__main__':
    main()
